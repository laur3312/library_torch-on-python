import torch

# 1. Загружаем подготовленные файлы
X_train = torch.load("X_train.pt")
y_train = torch.load("y_train.pt")
X_val = torch.load("X_val.pt")
y_val = torch.load("y_val.pt")

# 2. Создаем крутилки (веса W и смещение b) со случайными стартовыми числами
W = torch.randn(11, 1, requires_grad=True)
b = torch.randn(1, requires_grad=True)

# Устанавливаем скорость обучения (размер шага)
alpha = 0.01

print("--- Запуск цикла обучения нейросети ---")

# 3. Главный цикл обучения на 1000 эпох
for epoch in range(1000):
    # Делаем предсказание с помощью матричного умножения @
    y_hat = X_train @ W + b
    
    # Считаем ошибку MSE (среднее от квадратов разностей)
    loss = ((y_hat - y_train) ** 2).mean()
    
    # Включаем автодифф (рабочий бежит назад за подсказками)
    loss.backward()
    
    # Обновляем крутилки внутри безопасного блока без отслеживания истории
    with torch.no_grad():
        W -= alpha * W.grad
        b -= alpha * b.grad
        
        # Очищаем кармашки с подсказками перед новым кругом
        W.grad.zero_()
        b.grad.zero_()
        
    # Каждые 100 шагов показываем, как падает ошибка
    if epoch % 100 == 0:
        print(f"Эпоха {epoch}: Ошибка (Loss) = {loss:.5f}")

print("Обучение завершено!\n")

# 4. Проверяем модель на экзаменационных данных, которые она не видела
print("--- Экзамен модели на проверочных данных ---")
with torch.no_grad():
    y_hat_val = X_val @ W + b 

# Считаем средний абсолютный промах (на сколько баллов в среднем ошибается модель)
score = (y_hat_val - y_val).abs().mean()
print(f"Среднее отклонение на валидации: {score:.2f} балла.")