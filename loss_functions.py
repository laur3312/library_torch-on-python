import torch
from torch.nn import MSELoss, BCELoss, CrossEntropyLoss

# --- 1. MSELoss (Для регрессии: предсказание чисел) ---
loss_fn = MSELoss()
y = torch.tensor([[0.5], [1.5], [0.7]])       # Правильные ответы
y_hat = torch.tensor([[0.6], [0.2], [0.5]])   # Предсказания модели
# Считает: (y_hat - y)^2, затем берет среднее
print(loss_fn(y_hat, y))  # Выведет: 0.5800


# --- 2. BCELoss (Для выбора из 2-х классов: 0 или 1) ---
loss_fn = BCELoss()
y = torch.tensor([[1.0], [1.0], [0.0]])       # Правильный класс (0 или 1)
y_hat = torch.tensor([[0.9], [0.3], [0.2]])   # Вероятности от модели (от 0 до 1)
# Штрафует тем сильнее, чем дальше вероятность от ответа
print(loss_fn(y_hat, y))  # Выведет: 0.5365


# --- 3. CrossEntropyLoss (Для выбора из многих классов) ---
loss_fn = CrossEntropyLoss()
y2 = torch.tensor([1, 2, 0])  # Номера (индексы) правильных классов
y_hat1 = torch.tensor([
    [-1.2, 2.2, 0.2],   # Сырые очки модели для каждого класса
    [2.3, 0.2, 0.7],    # (PyTorch сам превратит их в вероятности)
    [0.9, -2.2, -1.2]
])
# Сравнивает, совпали ли максимальные очки с правильным индексом
print(loss_fn(y_hat1, y2))  # Выведет: 0.6868


# --- 4. Ошибка в процентах (MAPE) ---
y = torch.tensor([[0.5], [1.5], [0.7]])
y_hat = torch.tensor([[0.6], [0.2], [0.5]])

# Разница / Правильный ответ * 100%
score = (y - y_hat).abs() / y * 100
# Средний процент ошибки по всем примерам
print(score.mean())  # Выведет: 45.079411111111111 